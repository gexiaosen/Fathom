use std::ops::Range;
use std::sync::mpsc::Sender;

/// Map a UTF-16 offset inside `text` to a byte offset (char-boundary safe).
pub fn utf16_to_byte(text: &str, offset: usize) -> usize {
    let mut utf16 = 0;
    let mut byte = 0;
    for ch in text.chars() {
        if utf16 >= offset {
            break;
        }
        utf16 += ch.len_utf16();
        byte += ch.len_utf8();
    }
    byte
}

/// Append one IME callback record so the run can be verified from a log file.
pub fn log_ime_event(kind: &str, text: &str, range: Option<Range<usize>>) {
    // Opt-in only: the editor must never write an IME trace by default.
    let Ok(path) = std::env::var("FP_IME_LOG") else {
        return;
    };
    let line = format!(
        "{{\"event\":\"{}\",\"text\":\"{}\",\"chars\":{},\"range\":\"{:?}\"}}\n",
        kind,
        text.replace('\\', "\\\\").replace('"', "\\\""),
        text.chars().count(),
        range
    );
    if let Ok(mut f) = std::fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(path)
    {
        let _ = f.write_all(line.as_bytes());
    }
}

